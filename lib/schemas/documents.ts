/** One file's upload slot (requestUploadSlots). */
export interface IssuedSlot {
  /** The caller's row key, echoed back. */
  key: string;
  uploadId: string;
  bucket: "client-documents";
  path: string;
  signedUrl: string;
  token: string;
  /** The cleaned name the document will carry. */
  fileName: string;
  mimeType: string;
  expiresAt: string;
}

/** A confirmed upload (confirmUpload). */
export interface FinishedUpload {
  documentId: string;
  version: number;
  title: string;
  purpose: UploadPurpose;
  clientId: string;
  requestId: string | null;
  requestItemId: string | null;
  itemStatus: "pending" | "uploaded" | "accepted" | "rejected" | null;
  fileName: string;
  fileSize: number;
  /** Already confirmed earlier (a retried call): nothing new happened. */
  already: boolean;
}

/** A document of the client with the same SHA-256 (findDuplicates). */
export interface DuplicateMatch {
  sha256: string;
  documentId: string;
  title: string;
  fileName: string;
  version: number;
  isCurrent: boolean;
  category: string;
  financialYear: string | null;
  uploadedAt: string;
  inRecycleBin: boolean;
}
