/** The Documents tab's sub-tabs (§7.3.3 tab 6: vault, document requests, checklist). */
export const DOCUMENT_SUBTABS = ["vault", "requests", "checklist"] as const;
export type DocumentSubtab = (typeof DOCUMENT_SUBTABS)[number];

export function resolveDocumentSubtab(v: unknown): DocumentSubtab {
  const s = Array.isArray(v) ? v[0] : v;
  return (DOCUMENT_SUBTABS as readonly string[]).includes(String(s)) ? (s as DocumentSubtab) : "vault";
}

/**
 * Search-param names the Documents tab uses. The table state is the kit's own (`q`, `page`, `size`,
 * `sort`, `dir`: DataTable and FilterBar write those, and only one Client 360 tab shows at a time);
 * everything else is prefixed so it never collides with another tab.
 */
export const VAULT_PARAM = {
  subtab: "docs",
  category: "dcat",
  fy: "dfy",
  layout: "dview",
  bin: "dbin",
  expiring: "dexp",
  document: "doc",
  request: "request",
  requestStatus: "rstatus",
} as const;

/** Params kept when the vault's filters are cleared (the tab, the sub-tab, the layout, the bin). */
export const VAULT_PRESERVE = ["tab", "view", "sort", "dir", "size", "fy", "docs", "dview", "dbin"] as const;

/** "Expiring soon" in the vault: an expiry or renewal date within this many days (or already past). */
export const EXPIRING_WITHIN_DAYS = 30;

/** The FYs a document can be filed under: next FY, the current one and six before it (newest first). */
export function fyChoices(today: string = todayIST()): string[] {
  return [nextFinancialYear(financialYearOf(today)), ...recentFinancialYears(today, 7)];
}

export const VAULT_SORTS = ["created_at", "title", "category", "financial_year", "file_size"] as const;
export type VaultSort = (typeof VAULT_SORTS)[number];

