/**
 * Writes `supabase/seed/30_due_date_rules.sql` from the TypeScript seed, so the rule JSON in the
 * database is exactly what the calendar engine reads (§5.12, §6.7, §16):
 * - `DUE_DATE_RULE_SEED`, `DUE_DATE_OVERRIDE_SEED`, `CALENDAR_SEED_PARAMETERS`
 *   (lib/domain/statutory-calendar.ts);
 * - `SCALE_SEED_PARAMETERS` (lib/domain/scale.ts), the §6.6 statutory parameters.
 *
 *   npx tsx scripts/gen-due-date-seed.ts           write the file
 *   npx tsx scripts/gen-due-date-seed.ts --check   exit 1 when the file is out of date
 *
 * tests/unit/statutory-calendar.test.ts fails when the committed file and the TypeScript disagree.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { SeedParameterRow } from "@/lib/domain/gst";
import { SCALE_SEED_PARAMETERS } from "@/lib/domain/scale";
import {
  CALENDAR_SEED_PARAMETERS,
  DUE_DATE_OVERRIDE_SEED,
  DUE_DATE_RULE_SEED,
  type DueDateOverride,
  type DueDateRule,
} from "@/lib/domain/statutory-calendar";

/** The seed file, relative to the repository root. */
export const SEED_SQL_RELATIVE_PATH = join("supabase", "seed", "30_due_date_rules.sql");

/** A SQL string literal (single quotes doubled), or `null`. */
export function sqlText(value: string | null | undefined): string {
  return value === null || value === undefined ? "null" : `'${value.replace(/'/g, "''")}'`;
}

function sqlJson(value: unknown): string {
  return `${sqlText(JSON.stringify(value))}::jsonb`;
}

function sqlDate(value: string | null | undefined): string {
  return value === null || value === undefined ? "null" : `${sqlText(value)}::date`;
}

function ruleValues(r: DueDateRule): string {
  return `  (${[
    sqlText(r.code),
    sqlText(r.title),
    `${sqlText(r.complianceType)}::public.compliance_type`,
    sqlText(r.formCode),
    sqlJson(r.appliesTo),
    `${sqlText(r.frequency)}::public.service_frequency`,
    sqlJson(r.rule),
    String(r.reminderDays),
    sqlDate(r.effectiveFrom),
    sqlDate(r.effectiveTo),
    sqlText(r.sourceRef),
    String(r.verified),
    String(r.isActive),
  ].join(", ")})`;
}

function overrideValues(o: DueDateOverride): string {
  return `  (${[
    sqlText(o.ruleCode),
    sqlText(o.periodLabel),
    sqlDate(o.originalDue),
    sqlDate(o.extendedDue),
    sqlText(o.scope ?? null),
    sqlText(o.sourceRef),
  ].join(", ")})`;
}

function parameterValues(p: SeedParameterRow): string {
  return `  (${[
    sqlText(p.key),
    sqlJson(p.value),
    sqlDate(p.effectiveFrom),
    sqlDate(p.effectiveTo),
    sqlText(p.statute),
    sqlText(p.sectionRef),
    sqlText(p.sourceRef),
    sqlText(p.notes),
    String(p.verified),
  ].join(", ")})`;
}

const HEADER = `-- 30 · The statutory calendar (§6.7, §5.12, §16): due_date_rules, the CBDT Circular 07/2026
-- extensions in due_date_overrides, and the statutory_parameters the calendar and the scale decisions
-- read (§6.6 GST scheme and tax audit thresholds; §6.7 GST filing bar and ROC late fee).
-- §16 content only: law and its sources. No clients, no users, no demo data.
--
-- GENERATED by scripts/gen-due-date-seed.ts from lib/domain/statutory-calendar.ts and
-- lib/domain/scale.ts. Do not edit by hand: change the TypeScript and run
--   npx tsx scripts/gen-due-date-seed.ts
-- tests/unit/statutory-calendar.test.ts fails when this file and the TypeScript disagree.
--
-- Settled law is seeded verified = true; [verify] items verified = false, so the Law & rules page
-- lists them as "awaiting partner confirmation" (§6). Idempotent: on conflict do nothing, so
-- re-running never overwrites a rule, an extension or a verification a Partner has since recorded.
-- Rules take effect by PERIOD: a rule applies to periods starting on or after effective_from
-- (2025-04-01 = FY 2025-26, the first year this seed describes).
--
-- rule (jsonb), read by parseRuleSpec in lib/domain/statutory-calendar.ts:
--   {"monthOffset":1,"day":20}                       monthly: day 20 of the next month
--     + "monthsOfQuarter":[1,2]                      only months 1-2 of each FY quarter (IFF, PMT-06)
--     + "exceptions":[{"periodMonth":3,"monthOffset":1,"day":30}]   March -> 30 April (TDS deposit)
--   {"afterQuarterEnd":true,"monthOffset":1,"day":13} quarterly: day 13 of the month after the quarter
--     + "quarters":[4]                               only those FY quarters (TDS statement Q4)
--     + "stateDays":[{"day":22,"states":["22",...]}] state-dependent day; "day" is everyone else's
--   {"fixed":"07-31","yearOffset":1}                 annual: 31 July of (FY start year + 1)
--     + "period":"Q1"|"Q2"|"Q3"|"Q4"|"H1"|"H2"       a part of the FY (advance tax, MSME-1)
--   {"afterEvent":"AGM","days":30}                   30 days after the client's AGM (provisional:
--                                                    the AGM rule's 30 September until it is entered)
--   {"daysAfterPeriodEnd":180}                       180 days after the FY end (OPC AOC-4)
--   {"afterRuleDue":["TDS_RETURN_Q1",...],"days":15} 15 days after another rule's date (Form 16A)
--   {"everyNYears":3,"fixed":"06-30","per":"DIN"}    per DIN, every third FY after the last filing
--   extras: "formCode2025" (form under the Income-tax Act, 2025), "periodLabel":"taxYear"
--   (AY / Tax year labels), "filingBar" (GST 3-year bar), "lateFee" (ROC per-day fee),
--   "cumulativePercent" (advance tax), "note" (copied onto each event).
-- applies_to (jsonb), read by parseAppliesTo: serviceTypes, entityTypes, excludeEntityTypes,
--   gstScheme ("monthly"|"qrmp"|"composition" or a list), auditCase, taxAudit, tpCase,
--   presumptive, opc, minTurnover (rupees, applies ABOVE it), maxTurnover (rupees, up to and
--   including it), states (two-digit codes), optIn (generated only for clients with that flag).
`;

/** The full text of `supabase/seed/30_due_date_rules.sql`. */
export function renderDueDateSeedSql(): string {
  const parameters = [...SCALE_SEED_PARAMETERS, ...CALENDAR_SEED_PARAMETERS];
  return [
    HEADER,
    "insert into public.due_date_rules",
    "  (code, title, compliance_type, form_code, applies_to, frequency, rule, reminder_days, effective_from, effective_to, source_ref, verified, is_active)",
    "values",
    `${DUE_DATE_RULE_SEED.map(ruleValues).join(",\n")}`,
    "on conflict (code) do nothing;",
    "",
    "-- Government extensions are override rows, never rule changes (§5.12, §6.7).",
    "insert into public.due_date_overrides",
    "  (rule_code, period_label, original_due, extended_due, scope, source_ref)",
    "values",
    `${DUE_DATE_OVERRIDE_SEED.map(overrideValues).join(",\n")}`,
    "on conflict (rule_code, period_label) do nothing;",
    "",
    "-- statutory_parameters read by lib/domain/scale.ts (SCALE_PARAM_KEYS) and",
    "-- lib/domain/statutory-calendar.ts (CALENDAR_PARAM_KEYS). Amounts inside values are in RUPEES.",
    "insert into public.statutory_parameters",
    "  (key, value, effective_from, effective_to, statute, section_ref, source_ref, notes, verified)",
    "values",
    `${parameters.map(parameterValues).join(",\n")}`,
    "on conflict (key, effective_from) do nothing;",
    "",
  ].join("\n");
}

function main() {
  const path = join(__dirname, "..", SEED_SQL_RELATIVE_PATH);
  const sql = renderDueDateSeedSql();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(path, "utf8");
    } catch {
      // A missing file is out of date.
    }
    if (current !== sql) {
      console.error(`${SEED_SQL_RELATIVE_PATH} is out of date. Run: npx tsx scripts/gen-due-date-seed.ts`);
      process.exit(1);
    }
    console.log(`${SEED_SQL_RELATIVE_PATH} is up to date.`);
    return;
  }
  writeFileSync(path, sql, "utf8");
  console.log(`wrote ${SEED_SQL_RELATIVE_PATH} (${DUE_DATE_RULE_SEED.length} rules, ${DUE_DATE_OVERRIDE_SEED.length} overrides)`);
}

if (typeof require !== "undefined" && require.main === module) {
  main();
}
